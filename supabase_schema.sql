-- 8. Setup Auto-Profile Trigger for new auth signups
-- Automatically populates public.profiles whenever ANY user registers in auth.users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  clean_username TEXT;
  clean_user_id TEXT;
BEGIN
  clean_username := COALESCE(
    NULLIF(NEW.raw_user_meta_data->>'username', ''),
    NULLIF(split_part(NEW.email, '@', 1), ''),
    'athlete_' || substr(NEW.id::text, 1, 8)
  );

  clean_user_id := COALESCE(
    NULLIF(NEW.raw_user_meta_data->>'user_id', ''),
    'WS-' || upper(substr(md5(random()::text), 1, 6))
  );

  INSERT INTO public.profiles (
    id,
    user_id,
    full_name,
    username,
    email,
    phone,
    primary_sport,
    primary_role,
    profile_picture_url,
    is_verified
  )
  VALUES (
    NEW.id,
    clean_user_id,
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'full_name', ''), NEW.email),
    clean_username,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'phone', ''),
    COALESCE(NEW.raw_user_meta_data->>'primary_sport', 'cricket'),
    COALESCE(NEW.raw_user_meta_data->>'primary_role', 'Athlete'),
    COALESCE(NEW.raw_user_meta_data->>'profile_picture_url', ''),
    false
  )
  ON CONFLICT (id) DO UPDATE SET
    full_name = EXCLUDED.full_name,
    username = EXCLUDED.username,
    email = EXCLUDED.email,
    primary_sport = EXCLUDED.primary_sport,
    primary_role = EXCLUDED.primary_role,
    updated_at = NOW();

  INSERT INTO public.player_sport_stats (
    user_id,
    sport,
    stats_data
  )
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'primary_sport', 'cricket'),
    '{"matches_played": 0, "wins": 0, "rating": 1000}'::jsonb
  )
  ON CONFLICT (user_id, sport) DO NOTHING;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Re-create the trigger on auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 9. Backfill all existing auth.users into public.profiles
INSERT INTO public.profiles (
  id,
  user_id,
  full_name,
  username,
  email,
  phone,
  primary_sport,
  primary_role,
  profile_picture_url,
  is_verified
)
SELECT
  u.id,
  COALESCE(NULLIF(u.raw_user_meta_data->>'user_id', ''), 'WS-' || upper(substr(u.id::text, 1, 6))),
  COALESCE(NULLIF(u.raw_user_meta_data->>'full_name', ''), u.email),
  COALESCE(NULLIF(u.raw_user_meta_data->>'username', ''), split_part(u.email, '@', 1)),
  u.email,
  COALESCE(u.raw_user_meta_data->>'phone', ''),
  COALESCE(u.raw_user_meta_data->>'primary_sport', 'cricket'),
  COALESCE(u.raw_user_meta_data->>'primary_role', 'Athlete'),
  COALESCE(u.raw_user_meta_data->>'profile_picture_url', ''),
  false
FROM auth.users u
ON CONFLICT (id) DO UPDATE SET
  full_name = EXCLUDED.full_name,
  username = EXCLUDED.username,
  email = EXCLUDED.email;

