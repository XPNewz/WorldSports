-- 6. Create Permissive Policies for public.profiles
-- SELECT: anyone (logged in or guest) can discover registered athletes
CREATE POLICY "Public profiles are viewable by everyone"
  ON public.profiles FOR SELECT
  USING (true);

-- INSERT: allow registered/authenticated or onboarding users to create their profile
CREATE POLICY "Allow insert to profiles"
  ON public.profiles FOR INSERT
  WITH CHECK (true);

-- UPDATE: allow users to update their profile
CREATE POLICY "Allow update to profiles"
  ON public.profiles FOR UPDATE
  USING (true)
  WITH CHECK (true);

